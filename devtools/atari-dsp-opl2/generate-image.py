#!/usr/bin/env python3
"""Embed assembled Falcon OPL2 sources. No external project checkout is needed."""

import argparse
import hashlib
from pathlib import Path
from generate_dsp_stage2 import make_boot_image, make_program_stream, parse_lod, STAGE2_REPLY_OK


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bootstrap", type=Path, required=True)
    parser.add_argument("--program", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    boot = make_boot_image(args.bootstrap)
    stream, sections, words = make_program_stream(args.program)
    for section in parse_lod(args.program)[0]:
        if section.space != "P":
            continue
        if section.address < 0x200 and section.limit > 0x200:
            raise SystemExit("hot code exceeds internal P RAM")
        if section.address < 0x3f00 and section.limit > 0x2800:
            raise SystemExit("P code aliases waveform/stereo Y memory")
    source = Path(__file__).parent / "dsp/oplrt.asm"
    digest = hashlib.sha256(source.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    boot_bytes = [byte for word in boot for byte in ((word >> 16) & 255, (word >> 8) & 255, word & 255)]

    def array(name, ctype, values, width):
        rows = ["\t" + ", ".join(f"0x{value:0{width}x}" for value in values[i:i+8]) + ","
                for i in range(0, len(values), 8)]
        return f"static const {ctype} {name}[{len(values)}] = {{\n" + "\n".join(rows) + "\n};\n"

    text = ("/* Generated by devtools/atari-dsp-opl2/generate-image.py.\n"
            f" * oplrt.asm SHA-256: {digest}\n"
            " * SPDX-License-Identifier: GPL-3.0-or-later */\n"
            "#ifndef BACKENDS_MIXER_ATARI_OPL_DSP_IMAGE_H\n"
            "#define BACKENDS_MIXER_ATARI_OPL_DSP_IMAGE_H\n\n"
            f"#define ATARI_DSP_OPL_BOOT_WORDS {len(boot)}\n"
            f"#define ATARI_DSP_OPL_STREAM_WORDS {len(stream)}\n"
            f"#define ATARI_DSP_OPL_STREAM_REPLY_OK 0x{STAGE2_REPLY_OK:06x}\n\n"
            + array("kAtariDspOplBoot", "unsigned char", boot_bytes, 2)
            + array("kAtariDspOplStream", "uint32", stream, 6) + "\n#endif\n")
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"{words} program words in {sections} sections; {len(boot)} bootstrap words")


if __name__ == "__main__":
    main()
